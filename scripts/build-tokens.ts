// Builds src/styles/tokens.css from tokens/*.json.
//
// Output has three parts:
//   1. @theme        – primitives mapped onto Tailwind v4 theme namespaces. Tailwind's default
//                      palette, fonts, radii etc. are reset, so only design tokens exist as utilities.
//   2. @theme inline – scene roles (bg-scene, text-scene-fg, …) that resolve per scene at runtime.
//   3. .scene-*      – one class per scene that sets the role variables.
import { writeFile } from 'node:fs/promises'
import type { TransformedToken } from 'style-dictionary/types'
import { loadTokens, valueOf } from './tokens.ts'

const OUT_FILE = 'src/styles/tokens.css'

// Token path prefix → Tailwind v4 theme variable prefix.
const NAMESPACES: Record<string, string> = {
  color: '--color',
  'font.family': '--font',
  'font.weight': '--font-weight',
  text: '--text',
  leading: '--leading',
  tracking: '--tracking',
  radius: '--radius',
  height: '--height',
  breakpoint: '--breakpoint',
  border: '--border',
  duration: '--duration',
  easing: '--ease',
  blur: '--blur',
}

// Tailwind defaults to clear so off-system values can't sneak in via utilities.
const RESETS = [
  '--color-*',
  '--font-*',
  '--font-weight-*',
  '--text-*',
  '--leading-*',
  '--tracking-*',
  '--radius-*',
  '--breakpoint-*',
  '--ease-*',
  '--blur-*',
]

const SCENE_ROLES = ['bg', 'fg', 'accent', 'display', 'focus', 'shape', 'surface'] as const

function themeVar(token: TransformedToken): string | undefined {
  if (token.path.join('.') === 'spacing.base') return '--spacing'
  for (const [prefix, cssPrefix] of Object.entries(NAMESPACES)) {
    const prefixPath = prefix.split('.')
    if (prefixPath.every((part, i) => token.path[i] === part)) {
      return [cssPrefix, ...token.path.slice(prefixPath.length)].join('-')
    }
  }
  return undefined
}

/** `{color.pink.700}` → `var(--color-pink-700)`, so scenes stay linked to primitives. */
function referenceVar(token: TransformedToken): string {
  const original = String(token.original.$value)
  const ref = original.match(/^\{(.+)\}$/)?.[1]
  if (!ref) return valueOf(token)
  return `var(--color-${ref.split('.').slice(1).join('-')})`
}

const tokens = await loadTokens()
const primitives = tokens.filter((t) => t.path[0] !== 'scene')
const scenes = Map.groupBy(
  tokens.filter((t) => t.path[0] === 'scene'),
  (t) => t.path[1] ?? '',
)

const lines: string[] = [
  '/* Generated by scripts/build-tokens.ts from tokens/*.json. Do not edit by hand. */',
  '',
  '@theme {',
  ...RESETS.map((r) => `  ${r}: initial;`),
  '',
]
for (const token of primitives) {
  const name = themeVar(token)
  if (!name) throw new Error(`No Tailwind namespace for token ${token.path.join('.')}`)
  lines.push(`  ${name}: ${valueOf(token)};`)
}
lines.push('}', '', '@theme inline {')
for (const role of SCENE_ROLES) {
  const name = role === 'bg' ? 'scene' : `scene-${role}`
  lines.push(`  --color-${name}: var(--scene-${role});`)
}
lines.push('}')

for (const [scene, sceneTokens] of scenes) {
  lines.push('', `.scene-${scene} {`)
  for (const token of sceneTokens) {
    lines.push(`  --scene-${token.path[2]}: ${referenceVar(token)};`)
  }
  lines.push('  background-color: var(--scene-bg);', '  color: var(--scene-fg);', '}')
}

await writeFile(OUT_FILE, lines.join('\n') + '\n')
console.log(`Wrote ${OUT_FILE} (${primitives.length} primitives, ${scenes.size} scenes)`)
